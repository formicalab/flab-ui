#!/usr/bin/env python3
"""Regenerates www/js/pages/settings/zones.js from the IANA time zone database.

The router has no zoneinfo files, and /etc/config/system wants two values for a time zone: the IANA name
(`zonename`, for display) and the POSIX TZ rule (`timezone`, what the C library and BusyBox actually use).
The rule is the last line of every compiled tz file, so this script reads one rule per zone listed in zone.tab.

Usage (the `tzdata` package from PyPI carries the database):
    pip install tzdata
    python tools/gen-zones.py            # writes www/js/pages/settings/zones.js
    python tools/gen-zones.py --check    # exits 1 when the committed file is out of date
"""
import argparse
import importlib.metadata
import importlib.resources
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / 'www' / 'js' / 'pages' / 'settings' / 'zones.js'

# Zones that are not in zone.tab but are worth offering.
EXTRA = ['UTC']


def posix_rule(zone_file: pathlib.Path) -> str:
    """The POSIX TZ rule stored as the footer of a version 2+ tz file."""
    lines = zone_file.read_bytes().rstrip(b'\n').split(b'\n')
    return lines[-1].decode('ascii')


def build() -> str:
    """The text of zones.js for the installed tzdata."""
    root = pathlib.Path(str(importlib.resources.files('tzdata') / 'zoneinfo'))
    names = [line.split('\t')[2] for line in (root / 'zone.tab').read_text().splitlines() if line and not line.startswith('#')]
    names = sorted(set(names + EXTRA))
    version = importlib.metadata.version('tzdata')
    rows = [f"  '{n}': '{posix_rule(root / n)}'," for n in names]
    return (
        '// IANA time zone name -> POSIX TZ rule, generated by tools/gen-zones.py from tzdata '
        f'{version}. Do not edit by hand.\n'
        '// /etc/config/system keeps both: `zonename` (the name) and `timezone` (the rule).\n'
        'export const ZONES = {\n' + '\n'.join(rows) + '\n};\n')


def main() -> int:
    """Writes zones.js, or with --check compares it with the committed copy."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='compare with the committed file instead of writing it')
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        print('up to date' if current == text else 'out of date')
        return 0 if current == text else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {OUT} ({text.count(chr(10)) - 3} zones)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
