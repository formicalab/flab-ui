#Requires -Version 7.0
<#
.SYNOPSIS
Regenerates www/js/pages/settings/zones.js from the IANA time zone database.

.DESCRIPTION
The router has no zoneinfo files, and /etc/config/system wants two values for a time zone: the IANA name (zonename, for
display) and the POSIX TZ rule (timezone, what the C library and BusyBox actually use). The rule is the last line of every
compiled tz file, so this script reads one rule per zone listed in zone.tab.

The database comes from the tzdata wheel on PyPI (a zip file of compiled zoneinfo files), which is downloaded and
verified against the SHA-256 PyPI publishes; Python is not needed. Without -Check the newest tzdata is used unless
-TzdataVersion is given. With -Check the version recorded in the committed file is used, so the check only fails when
the file was edited or the generator changed, not when a newer tzdata is released.

.PARAMETER Check
Compare with the committed file instead of writing it; exits with code 1 when it is out of date.

.PARAMETER TzdataVersion
The tzdata version to use, for example 2026.6.

.PARAMETER WheelPath
A tzdata wheel (tzdata-<version>-py2.py3-none-any.whl) you already downloaded, used instead of downloading one. For a
network where files.pythonhosted.org cannot be reached; the version is taken from the file name.
#>
[CmdletBinding()]
param(
    [switch]$Check,
    [ValidatePattern('^\d+(\.\d+)*$')][string]$TzdataVersion,
    [string]$WheelPath
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$out = Join-Path (Join-Path (Join-Path (Join-Path (Split-Path $PSScriptRoot -Parent) 'www') 'js') 'pages') 'settings' | Join-Path -ChildPath 'zones.js'

# Zones that are not in zone.tab but are worth offering.
$extra = @('UTC')

#region Helpers
function Get-Wheel {
    <#
    .SYNOPSIS
    Downloads the tzdata wheel of a version from PyPI and returns the path of the verified file.
    .PARAMETER Version
    The tzdata version, or empty for the newest.
    .OUTPUTS
    A hashtable with Path (the wheel) and Version.
    #>
    param([string]$Version)

    $url = if ($Version) { "https://pypi.org/pypi/tzdata/$Version/json" } else { 'https://pypi.org/pypi/tzdata/json' }
    $meta = Invoke-RestMethod -Uri $url
    $file = @($meta.urls | Where-Object { $_.packagetype -eq 'bdist_wheel' })[0]
    if (-not $file) { throw "PyPI lists no tzdata wheel for version '$Version'." }
    $path = Join-Path ([IO.Path]::GetTempPath()) $file.filename
    Invoke-WebRequest -Uri $file.url -OutFile $path
    if ((Get-FileHash $path -Algorithm SHA256).Hash.ToLower() -ne $file.digests.sha256) { throw "The downloaded $($file.filename) does not match the SHA-256 PyPI publishes." }
    return @{ Path = $path; Version = $meta.info.version }
}

function Read-ZipText {
    <#
    .SYNOPSIS
    Reads one entry of a zip archive as ASCII text.
    .PARAMETER Archive
    An open ZipArchive.
    .PARAMETER Name
    The entry name, with forward slashes.
    .OUTPUTS
    String.
    #>
    param([Parameter(Mandatory)][IO.Compression.ZipArchive]$Archive, [Parameter(Mandatory)][string]$Name)

    $entry = $Archive.GetEntry($Name)
    if (-not $entry) { throw "The wheel has no entry $Name." }
    $reader = [IO.StreamReader]::new($entry.Open(), [Text.Encoding]::ASCII)
    try { return $reader.ReadToEnd() } finally { $reader.Dispose() }
}

function Get-ZonesText {
    <#
    .SYNOPSIS
    Builds the text of zones.js for a tzdata wheel.
    .DESCRIPTION
    For a version 2+ tz file the POSIX rule is the last line, between the final two newlines.
    .PARAMETER WheelPath
    Path of the tzdata wheel.
    .PARAMETER Version
    The tzdata version written into the header.
    .OUTPUTS
    String.
    #>
    param([Parameter(Mandatory)][string]$WheelPath, [Parameter(Mandatory)][string]$Version)

    $zip = [IO.Compression.ZipFile]::OpenRead($WheelPath)
    try {
        $tab = Read-ZipText $zip 'tzdata/zoneinfo/zone.tab'
        $names = [Collections.Generic.HashSet[string]]::new([string[]]$extra)
        foreach ($line in ($tab -split "`n")) {
            if ($line -and -not $line.StartsWith('#')) { [void]$names.Add($line.Split("`t")[2]) }
        }
        $sorted = [string[]]$names
        [Array]::Sort($sorted, [StringComparer]::Ordinal)

        $rows = foreach ($name in $sorted) {
            $lines = (Read-ZipText $zip "tzdata/zoneinfo/$name").TrimEnd("`n") -split "`n"
            "  '$name': '$($lines[-1])',"
        }
    }
    finally { $zip.Dispose() }

    return "// IANA time zone name -> POSIX TZ rule, generated by tools/gen-zones.ps1 from tzdata $Version. Do not edit by hand.`n" +
    "// /etc/config/system keeps both: ``zonename`` (the name) and ``timezone`` (the rule).`n" +
    "export const ZONES = {`n" + ($rows -join "`n") + "`n};`n"
}
#endregion

#region Main
Add-Type -AssemblyName System.IO.Compression.FileSystem

$current = if (Test-Path $out) { [IO.File]::ReadAllText($out) -replace "`r`n", "`n" } else { '' }
if (-not $TzdataVersion -and $Check -and $current -match 'from tzdata (\d+(?:\.\d+)*)\.') { $TzdataVersion = $Matches[1] }

if ($WheelPath) {
    if ((Split-Path $WheelPath -Leaf) -notmatch '^tzdata-(\d+(?:\.\d+)*)-.*\.whl$') { throw "Not a tzdata wheel: $WheelPath" }
    $wheel = @{ Path = (Resolve-Path $WheelPath).Path; Version = $Matches[1]; Downloaded = $false }
}
else {
    $wheel = Get-Wheel $TzdataVersion
    $wheel.Downloaded = $true
}
$text = Get-ZonesText -WheelPath $wheel.Path -Version $wheel.Version
if ($wheel.Downloaded) { Remove-Item $wheel.Path }

if ($Check) {
    if ($current -eq $text) { Write-Host 'up to date'; exit 0 }
    Write-Host 'out of date'
    exit 1
}

[IO.File]::WriteAllText($out, $text, [Text.UTF8Encoding]::new($false))
Write-Host "wrote $out ($(([regex]::Matches($text, "(?m)^  '")).Count) zones, tzdata $($wheel.Version))"
#endregion
