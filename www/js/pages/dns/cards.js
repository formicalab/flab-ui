// The sockets the resolver accepts queries on, one chip per address and port with its protocols. The wildcard address
// is marked "all addresses". Drawn inside the General area of the configuration, or alone when no resolver is installed.
function listeningPart(data, chips) {
  const both = data.engines?.unbound?.running && data.engines?.dnsmasq?.running;
  return chips.length
    ? h('div', {},
      h('p', { className: 'muted small dns-area-legend' }, '0.0.0.0 and [::] mean every IPv4 or IPv6 address of the router; any other address is one interface only. Clients reach the resolver on these.'),
      h('div', { className: 'chips' }, chips.map(c => h('span', { className: 'dns-sock' },
        h('span', { className: 'mono' }, c.text),
        h('span', { className: 'dns-proto' }, c.protos.join('/')),
        c.wildcard ? badge('all addresses', 'info') : null,
        both ? badge(engineName(c.engine), '') : null))))
    : h('div', { className: 'muted' }, data.engine ? 'The resolver is running, but no listening socket was found for it.' : 'No resolver is listening: nothing answers DNS queries on this router.');
}

// The control for one option, connected to the draft. `edit` is { canEdit, draft, inputs, touched, redraw } from the page: a
// described option of a single value is editable when the login may write; lists and options the page has no description
// for stay disabled (not editable yet).
function control(f, edit) {
  return fieldRow(f, {
    id: f.key,
    get: () => edit.draft.values[f.key],
    set: v => { edit.draft.values[f.key] = v; },
    disabled: !(edit.canEdit && isEditable(f)),
    touched: edit.touched,
    redraw: edit.redraw,
    register: (el, index) => { if (index == null) edit.inputs[f.key] = el; else (edit.inputs[f.key] ??= [])[index] = el; },
  });
}

// The controls of a section's fields. Fields that share a `group` in the schema and follow one another (DNS64 and its prefix) are
// drawn in one cell of the grid, one above the other, so a dependent option is never left alone on a row of its own.
function controls(fields, edit) {
  const out = [];
  for (let i = 0; i < fields.length; i++) {
    const f = fields[i];
    if (!f.group) { out.push(control(f, edit)); continue; }
    const members = [f];
    while (fields[i + 1]?.group === f.group) members.push(fields[++i]);
    out.push(h('div', { className: 'set-group' }, members.map(m => control(m, edit))));
  }
  return out;
}

// Which areas are open, kept across the redraws of the poll (an area missing here starts as the schema says).
const opened = new Map();

// The domains Unbound exempts from rebind protection (`private-domain:`), as the plugin read them from UCI's generated
// configuration and from the srv file: a read-only block of the Security and privacy area. There is no UCI option for the list,
// so it is changed in /etc/unbound/unbound_srv.conf; the page only shows it, folded, because it can be long.
function privateDomainsBlock(data) {
  const list = data.private_domains ?? [];
  const file = list.filter(x => x.source === 'file').length;
  const uci = list.length - file;
  const names = [...list].sort((a, b) => a.name.localeCompare(b.name));
  return h('section', { className: 'dns-sec dns-priv-sec' },
    h('h4', { className: 'dns-sec-title' }, 'Rebind exceptions from the files'),
    h('p', { className: 'muted small dns-area-legend' }, list.length
      ? `${list.length} domain${list.length === 1 ? '' : 's'} may resolve to private addresses although rebind protection is on${data.truncated?.private_domains ? ' (list cut)' : ''}: ${uci} generated by UCI for the local names and ${file} listed in /etc/unbound/unbound_srv.conf. There is no UCI option for this list (OpenWrt's Unbound scripts only write private-domain for the local domain and the router's own name), so this page cannot change it; edit that file and restart Unbound.`
      : 'No domain is exempt from rebind protection.'),
    list.length ? disclosure({
      cls: 'dns-priv', summary: 'Show the domains', open: opened.get('private') ?? false, onToggle: open => opened.set('private', open),
      body: h('div', { className: 'dns-priv-list mono' }, names.map(x => h('span', { title: x.source === 'file' ? 'Listed in /etc/unbound/unbound_srv.conf' : 'Generated by UCI for the local names' }, x.name))),
    }) : null);
}

// The resolver's options as the shared controls, in collapsible areas (General first, then Security and privacy, then the
// rest), each with its sections: a checkbox for a yes/no option, a drop-down for a fixed set of values, a number input for a
// number, a text box for a name and a list for several values. A folded area still shows its state in one line. The General
// area also shows where the resolver listens, after its service and monitoring options. Edits are
// saved with the review banner of the command bar (see index.js).
function configPart(data, e, file, edit, chips) {
  // One collapsible area: its sections of controls and a one-line state summary in the header.
  const area = a => {
    const sections = a.sections.map(s => h('section', { className: 'dns-sec' },
      s.title ? h('h4', { className: 'dns-sec-title' }, s.title) : null,
      h('div', { className: 'set-fields' }, controls(s.fields, edit))));
    if (a.id === 'general') sections.splice(1, 0, h('section', { className: 'dns-sec dns-listen' }, h('h4', { className: 'dns-sec-title' }, 'Listening on'), listeningPart(data, chips)));
    return disclosure({
      cls: 'dns-area fl-disclosure-bar', open: opened.get(a.id) ?? a.open, onToggle: open => opened.set(a.id, open),
      summary: [h('span', { className: 'dns-area-title' }, a.title), h('span', { className: 'dns-area-count muted' }, `${a.count} options`), a.summary ? h('span', { className: 'dns-area-sum muted' }, a.summary) : null],
      body: h('div', { className: 'dns-area-body' },
        h('p', { className: 'muted small dns-area-legend' }, a.legend),
        sections,
        a.id === 'security' && e === 'unbound' ? privateDomainsBlock(data) : null),
    });
  };
  return h('div', {},
    legend(edit.canEdit ? [
      `These are the settings of ${engineName(e)} in ${file}. Saving applies a change at once. If it breaks something, the router restores the previous settings within 30 seconds.`,
      `An empty box or a "Default" choice means the option is not set, so the default applies. Options not listed here can only be edited by hand in ${file}. Zones are edited in the Zones card.`]
      : [`Read only: this page shows the settings of ${engineName(e)} but this login cannot change them. Edit ${file} and restart the service to change one.`,
        'An empty box or a "Default" choice means the option is not set, so the default applies.']),
    h('div', { className: 'dns-areas' }, configAreas(data).map(area)));
}

// The full-width card at the top: the resolver's configuration, with where it listens in the General area. Without a
// resolver there is nothing to configure, and the card is only the listening part.
export function resolverCard(data, edit) {
  const chips = listenerChips(data);
  const e = subject(data);
  const file = e === 'unbound' ? '/etc/config/unbound' : '/etc/config/dhcp';
  const listening = chips.length ? `${chips.length} address${chips.length === 1 ? '' : 'es'} and port${chips.length === 1 ? '' : 's'}${data.truncated?.listeners ? ' (cut)' : ''}` : 'not listening';
  if (!e) return card([icon('broadcast'), 'Listening on', h('span', { className: 'sub' }, listening)], h('div', { className: 'dns-pad' }, listeningPart(data, chips)));
  // Like the daemon card of the DHCP page: green when the resolver this card describes runs, red when it does not.
  const running = data.engines?.[e]?.running ?? Boolean(data.engine);
  const port = data.engines?.[e]?.port;
  const state = badge(`${engineName(e)} ${running ? 'running' : 'not running'}`, running ? 'success' : 'danger',
    running ? `${engineName(e)} is running${port ? ` and answers on port ${port}` : ''}.` : `${engineName(e)} is configured but not running, so nothing answers DNS queries from it.`);
  return card([icon('gear'), 'Configuration', state, h('span', { className: 'sub' }, `${file} · ${listening}`)],
    configPart(data, e, file, edit, chips));
}

